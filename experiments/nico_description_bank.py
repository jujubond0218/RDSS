def build_bank():
    texts,metadata={},{}
    for name,features in FEATURES.items():
        assert len(features)==10 and len(CONFUSERS[name])==5
        texts[name],metadata[name]=[],[]
        def add(text,kind,context='neutral'):
            texts[name].append(text);metadata[name].append({'kind':kind,'context':context})
        for prefix in ['A photograph','A close view']:
            for feature in features:add(f'{prefix} of a {name}: {feature}.','generic')
        for context,scene in CONTEXTS.items():
            for feature in features:add(f'A {name} {scene}; {feature}.','context_detail',context)
        for prefix in ['In this image','In a close view','In a full view','From its visible outline']:
            for other in CONFUSERS[name]:
                add(f'{prefix}, a {name} has this distinguishing appearance: {features[0]}, unlike a {other}.','contrast')
        assert len(texts[name])==100
    return texts,metadata
