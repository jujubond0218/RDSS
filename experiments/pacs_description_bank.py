STYLES = {
 'photo':'A realistic color photograph of a {name}: {clause}.',
 'art_painting':'An oil painting of a {name}, with painted colors and brush strokes: {clause}.',
 'cartoon':'A cartoon illustration of a {name}, with simplified shapes and bold outlines: {clause}.',
 'sketch':'A black-and-white line sketch of a {name}, with unfilled contours on paper: {clause}.'
}


def build_bank():
    texts, metadata = {}, {}
    for name,clauses in CLAUSES.items():
        assert len(clauses)==25
        texts[name],metadata[name] = [],[]
        for style,template in STYLES.items():
            for i,clause in enumerate(clauses):
                texts[name].append(template.format(name=name,clause=clause))
                metadata[name].append({'style':style,'kind':'overview' if i<5 else 'detail' if i<20 else 'contrast'})
        assert len(texts[name])==100
    return texts,metadata
